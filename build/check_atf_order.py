#!/usr/bin/env python3
"""Check the channel order of the MCAS far-field ATFs against the device's own microphone layout.

    python build/check_atf_order.py [take]

The MCAS ATF release (aria_atfs.pkl) does not document its channel order. build_atf.py applies
the permutation (0,1,2,3,4,6,5) -- the two rear microphones swapped -- so that ATF channel k is device
mic k, the order of the VRS audio channels. This script re-derives that from scratch:

  1. Device layout: the CAD extrinsics of mic0..mic6 from the take's VRS calibration (projectaria_tools,
     getT_Cpf_Sensor with CAD values: Aria microphones have no factory-calibrated extrinsics), remapped
     from the CPF (+x left, +y up, +z forward) to the array frame (+x forward, +y left, +z up).
  2. Permutation search: for every one of the 7! = 5040 assignments of ATF channels to device mics, the
     RMS difference between the ATFs' measured pairwise TDOAs (peak sample of each far-field ATF) and the
     plane-wave TDOAs the CAD layout predicts, over every far-field direction. The measured TDOAs include
     the head (the ATFs were measured on a HATS), so no assignment fits exactly; the question is which
     fits best, and by how much.
  3. Sign check: for a source at +90 deg (the wearer's left), the rear-left microphone must hear it first.

Read-only: writes results/build/atf_channel_order.md and prints it.
"""
from __future__ import annotations

import itertools
import pickle
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from paths import CFG, RAW  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
C, FS = 343.0, 48000.0
APPLIED = (0, 1, 2, 3, 4, 6, 5)                    # build_atf.CH_PERM
CPF_TO_ARRAY = np.array([[0.0, 0.0, 1.0],          # array x = CPF z (forward)
                         [1.0, 0.0, 0.0],          # array y = CPF x (left)
                         [0.0, 1.0, 0.0]])         # array z = CPF y (up)


def cad_layout(take: str) -> tuple[list[str], np.ndarray]:
    from projectaria_tools.core import data_provider
    room = take.split("_")[0]
    rc = CFG["rooms"][room]
    vrs = RAW / rc["aria_dir"] / rc["takes"][take]["vrs"]
    calib = data_provider.create_vrs_data_provider(str(vrs)).get_device_calibration()
    labels = [m.get_label() for m in calib.get_aria_microphone_calib()]
    p = np.array([np.asarray(calib.get_transform_cpf_sensor(l, True).translation()).ravel()[:3] for l in labels])
    return labels, p @ CPF_TO_ARRAY.T


def main() -> int:
    take = sys.argv[1] if len(sys.argv) > 1 else "office_maleSpeech_static"
    labels, pos = cad_layout(take)
    d = pickle.load(open(CFG["chime_atf_pkl"], "rb"))
    ff = np.asarray(d["far_field"], float)                       # taps x 7 x dirs, as distributed
    az, el, _ = np.asarray(d["directions"], float)
    u = np.stack([np.cos(np.radians(el)) * np.cos(np.radians(az)),
                  np.cos(np.radians(el)) * np.sin(np.radians(az)), np.sin(np.radians(el))], 1)
    arrive = -(u @ pos.T) / C * FS                               # dirs x mics: plane-wave arrival (samples)
    peak = np.argmax(np.abs(ff), axis=0).T.astype(float)        # dirs x ATF channels
    I, J = np.triu_indices(7, 1)
    pred = arrive[:, I] - arrive[:, J]
    rms = {}
    for perm in itertools.permutations(range(7)):              # ATF channel perm[k] is device mic k
        m = peak[:, perm]
        rms[perm] = float(np.sqrt(np.mean((m[:, I] - m[:, J] - pred) ** 2)))
    rank = sorted(rms, key=rms.get)
    ident = tuple(range(7))
    corr = lambda perm: float(np.corrcoef((peak[:, perm][:, I] - peak[:, perm][:, J]).ravel(), pred.ravel())[0, 1])
    # sign check on the horizontal ring
    ring = np.where(np.abs(el) < 1e-6)[0]
    az_w = (az + 180) % 360 - 180
    onset = lambda f, i: [int(np.argmax(np.abs(f[:, c, i]) > 0.2 * np.abs(f[:, c, i]).max())) for c in range(7)]
    left = ring[np.argmin(np.abs(az_w[ring] - 90))]
    o_raw, o_fix = onset(ff, left), onset(ff[:, list(APPLIED), :], left)
    rear = sorted(range(7), key=lambda k: pos[k, 0])[:2]       # the two rearmost mics
    lines = ["# MCAS far-field ATF channel order", "",
             f"Generated by `build/check_atf_order.py {take}`: the CAD layout from that take's VRS calibration, "
             f"the ATFs from {Path(CFG['chime_atf_pkl']).name} ({ff.shape[2]} far-field directions).", "",
             "## Device layout (CAD extrinsics, array frame: +x forward, +y left, +z up; cm)", "",
             "| Channel | Label | x | y | z |", "|---|---|---|---|---|"]
    lines += [f"| {k} | {labels[k]} | {100 * pos[k, 0]:+.1f} | {100 * pos[k, 1]:+.1f} | {100 * pos[k, 2]:+.1f} |"
              for k in range(7)]
    side = lambda k: "left" if pos[k, 1] > 0 else "right"
    lines += ["", f"Rearmost pair: {labels[rear[0]]} ({side(rear[0])}) and {labels[rear[1]]} ({side(rear[1])}).", "",
              "## Permutation search (RMS pairwise-TDOA misfit, samples at 48 kHz, over every direction)", "",
              "| Assignment | RMS (samples) | Rank of 5040 | Correlation |", "|---|---|---|---|",
              f"| as distributed {ident} | {rms[ident]:.2f} | {rank.index(ident) + 1} | {corr(ident):.2f} |",
              f"| applied {APPLIED} | {rms[APPLIED]:.2f} | {rank.index(APPLIED) + 1} | {corr(APPLIED):.2f} |",
              f"| runner-up {rank[1]} | {rms[rank[1]]:.2f} | 2 | {corr(rank[1]):.2f} |",
              "", f"Best: {rank[0]}.", "",
              "## Sign check: source at +90 deg (the wearer's left)", "",
              f"- As distributed: channel 5 onset {o_raw[5]}, channel 6 onset {o_raw[6]} samples.",
              f"- Permuted: channel 5 ({labels[5]}, {side(5)}) onset {o_fix[5]}, channel 6 ({labels[6]}, {side(6)}) "
              f"onset {o_fix[6]} samples: the {'left' if o_fix[5] < o_fix[6] else 'RIGHT'} rear mic hears it first.", ""]
    md = "\n".join(lines)
    out = ROOT / "results" / "build"
    out.mkdir(parents=True, exist_ok=True)
    (out / "atf_channel_order.md").write_text(md)
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
