#!/usr/bin/env python3
"""RQ1: the glasses' own pose (MPS SLAM) against OptiTrack, on the L-shape takes OptiTrack tracked.

    python analysis/pose.py

Each tracked moving take (walking and head-only) was built twice from identical audio: with the
SLAM pose and with the OptiTrack pose (the *Opti twin). Both twins share the placement and the
reference instant, so the pose is the only difference (config/rooms.json). The walking twins are
placed from the OptiTrack geometry and trimmed to the span OptiTrack covers completely; the
head-only twins are placed from the speech (the wearer stays on the mark), untrimmed, and their few
OptiTrack gaps are filled from SLAM.

  what the pipeline uses   the motion-aware model reads only the yaw and the horizontal
                           translation, each relative to the take's own reference pose
                           (prepAriaTake: rotYaw, transAzi, transRad). Compared sample by sample
                           between the twins, where the OptiTrack twin's pose is OptiTrack's own,
                           beside how far the wearer turned and moved
  tracking agreement       the whole recording, after the best rigid alignment of the two world
                           frames (build/geometry_placement.py, stored in results/build/<take>.json)
  the result               the twins' T20 (T_mid) and DRR (repo window) errors from
                           results/pipeline/summary.csv. The omni model does not use the pose, so
                           its rows must be identical between twins: checked

The OptiTrack-to-glasses link (hand-eye rotation and lever arm, rooms.json optitrack_link) was
fitted on the two head-moving takes: there the agreement is partly in-sample, so optimistic, and
those takes are marked. The walking takes are out of sample. Four takes: the result rows are a
reading of these takes, not a test. Writes results/pose/summary.md.
"""
from __future__ import annotations

import csv
import json
import math
from pathlib import Path

import numpy as np
import scipy.io as sio

import stats as S

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "pose"
ROOMS = json.loads((ROOT / "config" / "rooms.json").read_text())["rooms"]
MOVEMENTS = {"fullMove": "Walking", "headMove": "Head-only"}
CONDITIONS = {"informed_motionAware": "Informed (MA)", "blind_motionAware": "Blind (MA)"}
POSE = ["rotationYawPitchRollRad", "translationXYZCart", "referencePos", "referenceRotationAziEleRad", "fs"]
MARK = "†"


def twins() -> list[dict]:
    """Every take built with the OptiTrack pose and its SLAM twin, walking first; `in_sample` if the
    OptiTrack link was fitted on its recording."""
    out = []
    for rc in ROOMS.values():
        fitted = set(rc.get("optitrack_link", {}).get("fitted_on", []))
        for t, tc in rc["takes"].items():
            if tc.get("pose_source") == "optitrack":
                mov = next(m for m in MOVEMENTS if f"_{m}" in t)
                out.append({"slam": t[:-len("Opti")], "opti": t, "movement": mov,
                            "in_sample": Path(tc["vrs"]).stem in fitted})
    return sorted(out, key=lambda p: (list(MOVEMENTS).index(p["movement"]), p["slam"]))


def model_pose(take: str, extra=()) -> dict:
    """The pose as prepAriaTake hands it to the motion-aware model: yaw and horizontal translation
    relative to the reference pose."""
    d = sio.loadmat(ROOT / "data" / "rooms" / f"{take}.mat", variable_names=POSE + list(extra), squeeze_me=True)
    xy = d["translationXYZCart"][:, :2] - np.asarray(d["referencePos"], float)[:2]
    yaw = d["rotationYawPitchRollRad"][:, 0] - np.asarray(d["referenceRotationAziEleRad"], float)[0]
    return {"yaw": yaw, "xy": xy, "fs": float(d["fs"]), **{k: d[k] for k in extra}}


def spread(v: np.ndarray) -> str:
    return f"{np.median(v):.2f} / {np.percentile(v, 90):.2f} / {np.max(v):.2f}"


def label(p: dict) -> str:
    return p["slam"] + (f" {MARK}" if p["in_sample"] else "")


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    pairs = twins()
    summ = {(r["take"], r["condition"]): r for r in csv.DictReader(open(ROOT / "results" / "pipeline" / "summary.csv"))}
    lines = ["# RQ1: SLAM pose against OptiTrack\n",
             f"Generated by `analysis/pose.py`. {len(pairs)} L-shape takes, each built with the SLAM pose and with "
             f"the OptiTrack pose from identical audio. {MARK} the OptiTrack-to-glasses link was fitted on this take "
             "(partly in-sample, so optimistic); the others are out of sample.\n",
             "## What the pipeline uses\n",
             "Yaw and horizontal translation relative to each take's reference pose, SLAM minus OptiTrack, "
             "sample by sample where the OptiTrack twin's pose is OptiTrack's own. |difference| as median / 90th "
             "percentile / max. Heading range: the 5-95 % range of the unwrapped yaw (over 360 deg: more than a "
             "full turn).\n",
             "| Take | Movement | Compared (s, % of take) | Heading range (deg) | Max displacement (m) "
             "| |yaw difference| (deg) | |translation difference| (cm) |",
             "|---|---|---|---|---|---|---|"]
    for p in pairs:
        a, b = model_pose(p["slam"]), model_pose(p["opti"], extra=["poseIsOptitrack"])
        m = np.asarray(b["poseIsOptitrack"], float) > 0.5
        dyaw = np.degrees(np.abs((a["yaw"] - b["yaw"] + np.pi) % (2 * np.pi) - np.pi))[m]
        dxy = 100 * np.linalg.norm(a["xy"] - b["xy"], axis=1)[m]
        yaw = np.degrees(np.unwrap(a["yaw"]))
        lines.append(f"| {label(p)} | {MOVEMENTS[p['movement']]} | {m.sum() / a['fs']:.1f} ({100 * m.mean():.1f} %) | "
                     f"{np.percentile(yaw, 95) - np.percentile(yaw, 5):.0f} | "
                     f"{np.max(np.linalg.norm(a['xy'], axis=1)):.2f} | {spread(dyaw)} | {spread(dxy)} |")

    lines += ["", "## Tracking agreement\n",
              "The whole recording, after the best rigid alignment of the two world frames (the build's check; "
              "rotation is the full 3-D angle, not only yaw).\n",
              "| Take | Movement | Position, median / 90th pct (cm) | Rotation, median / 90th pct (deg) |",
              "|---|---|---|---|"]
    for p in pairs:
        v = json.loads((ROOT / "results" / "build" / f"{p['opti']}.json").read_text())["optitrack"]["vs_mps"]
        lines.append(f"| {label(p)} | {MOVEMENTS[p['movement']]} | {v['vs_mps_pos_median_cm']:.1f} / "
                     f"{v['vs_mps_pos_p90_cm']:.1f} | {v['vs_mps_rot_median_deg']:.1f} / {v['vs_mps_rot_p90_deg']:.1f} |")

    lines += ["", "## The result\n",
              f"|T20 error| ({S.PRIMARY}, %) and |DRR error| (repo window, dB) with each pose; difference = SLAM "
              "minus OptiTrack (positive: SLAM worse).\n",
              "| Take | Movement | Condition | T20 SLAM | T20 OptiTrack | difference | DRR SLAM | DRR OptiTrack "
              "| difference |",
              "|---|---|---|---|---|---|---|---|---|"]
    bands = S.BAND_SETS[S.PRIMARY]
    for p in pairs:
        for cond, name in CONDITIONS.items():
            rs, ro = summ[(p["slam"], cond)], summ[(p["opti"], cond)]
            ts, to = S.t20_err(rs, bands), S.t20_err(ro, bands)
            ds, do = abs(S.num(rs["drrErr"])), abs(S.num(ro["drrErr"]))
            lines.append(f"| {label(p)} | {MOVEMENTS[p['movement']]} | {name} | {ts:.1f} | {to:.1f} | {ts - to:+.1f} | "
                         f"{ds:.2f} | {do:.2f} | {ds - do:+.2f} |")
    cols = [f"t20Err_{b}" for b in S.BANDS] + ["drrErr", "drrErrPaper"]
    same = all(math.isclose(S.num(summ[(p["slam"], c)][k]), S.num(summ[(p["opti"], c)][k]), rel_tol=0, abs_tol=1e-9)
               for p in pairs for c in ("informed_omni", "blind_omni") for k in cols)
    lines.append("\nThe omni model's rows are " + ("identical between twins (it does not use the pose), so the pose "
                 "is the only difference." if same else "NOT identical between twins: something other than the "
                 "pose differs."))
    md = "\n".join(lines) + "\n"
    (OUT / "summary.md").write_text(md)
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
