#!/usr/bin/env python3
"""RQ3, step 1: oracle early-reflection removal, read against the front-end anchors.

    python analysis/dereverb.py

Reads results/dereverb/eval/<take>_<candidate>.csv (pipeline/evalDereverb.m, the
candidates from dereverb/oracle.py) and the front-end anchors
(results/frontend/<take>_anchors.csv). For the takes where the wearer does not walk:

  the pseudo-reference   early residual (2.5-20 ms re the direct path) and coherence
  T20                    deviation from the informed estimate of the same take (T_mid,
                         frontend.deviation: the primary measure), and |error| against the
                         omni reference
  DRR                    |error|, both windows
  headroom recovered     (dev(today) - dev(candidate)) / (dev(today) - dev(perfect_frontend)),
                         from the means; today = wpe_oracle_steering
  paired tests           each candidate against wpe_oracle_steering

and the passthrough check (the unmodified reference through the harness, which must
reproduce wpe_oracle_steering). Writes results/dereverb/summary.md.
"""
from __future__ import annotations

import csv
import glob
from pathlib import Path

import numpy as np

import frontend as F
import stats as S

ROOT = Path(__file__).resolve().parents[1]
EVAL = ROOT / "results" / "dereverb" / "eval"
OUT = ROOT / "results" / "dereverb"
TODAY, CEILING = "wpe_oracle_steering", "perfect_frontend"
CANDIDATES = {"oracle_comb": "Floor echo, simple model", "oracle_floor": "Floor echo, as measured",
              "oracle_early_sub": "All early reflections (subtracted)",
              "oracle_early": "All early reflections (inverse filter)",
              "oracle_fixed": "Fixed part only (time-varying residual removed)",
              "oracle_perfect_resid": "Perfect front end + today's non-fixed residual"}
LADDER = [TODAY, *CANDIDATES, CEILING]
NAMES = {TODAY: "Today (WPE, oracle steering)", **CANDIDATES, CEILING: "Perfect front end"}


def load() -> dict:
    data = F.load()["all"]
    for f in glob.glob(str(EVAL / "*.csv")):
        for r in csv.DictReader(open(f)):
            if r["take"] in data:
                data[r["take"]][(r["label"], r["model"])] = r
    return data


def still(data: dict, label: str) -> list[str]:
    """Takes where the wearer does not walk and both label and today exist."""
    return sorted(t for t in data if F.movement(t) in ("static", "headMove")
                  and (label, "motionAware") in data[t] and (TODAY, "motionAware") in data[t])


def mean(data, takes, fn) -> float:
    v = [fn(t) for t in takes]
    v = [x for x in v if np.isfinite(x)]
    return float(np.mean(v)) if v else float("nan")


def main() -> int:
    data = load()
    T = still(data, TODAY)
    if not T:
        raise SystemExit("no evaluated candidates yet")
    num = lambda t, l, c: S.num(data[t][(l, "motionAware")][c]) if (l, "motionAware") in data[t] else np.nan
    lines = [f"# RQ3 step 1: oracle early-reflection removal\n",
             f"Generated by `analysis/dereverb.py`. Takes where the wearer does not walk: {len(T)}; "
             f"each candidate's row says how many it has been scored on. Motion-aware RLS unless stated. Deviation = |T20 relative error minus that of "
             f"the informed estimate of the same take| at 500 Hz and 1 kHz (pp); signed mean in brackets "
             f"(positive = T20 too long).\n"]

    # passthrough check
    pt = sorted(t for t in data if ("passthrough", "motionAware") in data[t])
    if pt:
        lines.append("## Check: the unmodified reference through the harness\n")
        lines.append("| Take | Model | T_mid error, passthrough / anchors | DRR error, passthrough / anchors |")
        lines.append("|---|---|---|---|")
        for t in pt:
            for m in ("motionAware", "omni"):
                a, b = data[t][("passthrough", m)], data[t][(TODAY, m)]
                lines.append(f"| {t} | {m} | {F.METRICS[F.PRIMARY][0](a):.2f} / {F.METRICS[F.PRIMARY][0](b):.2f} | "
                             f"{S.num(a['drrErr']):+.2f} / {S.num(b['drrErr']):+.2f} |")
        lines.append("")

    # main table
    lines.append("## The ladder with the oracle candidates (means)\n")
    lines.append("| Condition | Takes | Early residual (dB) | Coherence | Deviation, MA | Deviation, omni | "
                 "T_mid error vs omni ref | DRR error (repo / paper window) |")
    lines.append("|---|---|---|---|---|---|---|---|")
    dev = {}
    for lab in LADDER:
        Tl = [t for t in T if (lab, "motionAware") in data[t]]
        dev[lab] = {m: mean(data, Tl, lambda t: F.deviation(data, t, lab, m)) for m in ("motionAware", "omni")}
        sg = mean(data, Tl, lambda t: F.deviation(data, t, lab, "motionAware", True))
        lines.append(
            f"| {NAMES[lab]} | {len(Tl)} | {mean(data, Tl, lambda t: num(t, lab, 'refEarlyDb')):+.1f} | "
            f"{mean(data, Tl, lambda t: num(t, lab, 'refCohEff')):.3f} | {dev[lab]['motionAware']:.1f} ({sg:+.1f}) | "
            f"{dev[lab]['omni']:.1f} | {mean(data, Tl, lambda t: F.value(data, t, lab, 'motionAware', F.PRIMARY)):.1f} | "
            f"{mean(data, Tl, lambda t: abs(num(t, lab, 'drrErr'))):.2f} / "
            f"{mean(data, Tl, lambda t: abs(num(t, lab, 'drrErrPaper'))):.2f} |")
    lines.append("")

    # headroom recovered and paired tests
    lines.append("## Against today\n")
    lines.append("Share of the headroom recovered = (deviation today - candidate) / (deviation today - perfect "
                 "front end), from the means. Tests: candidate minus today, paired by take.\n")
    for lab, name in CANDIDATES.items():
        Tl = [t for t in T if (lab, "motionAware") in data[t]]
        share = {m: (dev[TODAY][m] - dev[lab][m]) / (dev[TODAY][m] - dev[CEILING][m]) for m in ("motionAware", "omni")}
        lines.append(f"**{name}** ({len(Tl)} takes): headroom recovered {100 * share['motionAware']:.0f}% "
                     f"(motion-aware), {100 * share['omni']:.0f}% (omni)\n")
        for m in ("motionAware", "omni"):
            r = S.paired([F.deviation(data, t, lab, m) - F.deviation(data, t, TODAY, m) for t in Tl])
            lines.append(f"- deviation, {m}: {S.fmt_paired(r, 'pp')}")
        r = S.paired([abs(num(t, lab, "drrErr")) - abs(num(t, TODAY, "drrErr")) for t in Tl])
        lines.append(f"- |DRR error|, motion-aware: {S.fmt_paired(r, 'dB')}")
        lines.append("")

    # per room
    lines.append("## Per room (deviation, motion-aware)\n")
    lines.append("| Room | Takes | " + " | ".join(NAMES[l] for l in LADDER) + " |")
    lines.append("|---|---|" + "---|" * len(LADDER))
    for room in F.ROOM_SETS["all"]:
        Tr = [t for t in T if t.split("_")[0] == room]
        if Tr:
            lines.append(f"| {room} | {len(Tr)} | " + " | ".join(
                f"{mean(data, Tr, lambda t: F.deviation(data, t, l, 'motionAware')):.1f}" for l in LADDER) + " |")
    md = "\n".join(lines) + "\n"
    (OUT / "summary.md").write_text(md)
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
