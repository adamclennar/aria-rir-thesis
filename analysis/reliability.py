#!/usr/bin/env python3
"""How reliable is each octave band's T20, and where do the large errors in the extreme bands
come from?

    python analysis/reliability.py

Reads results/reliability/ref_t20_per_sweep.csv (pipeline/refT20Repeatability.m) and writes
results/reliability/summary.md:

  reference repeatability  the scoring's T20 estimator on each omni sweep separately: the
                           sweep-to-sweep spread, an upper bound on the uncertainty of the mean
                           IR the scoring uses. It cannot see position dependence: below the
                           Schroeder frequency the field is modal, so T20 can be repeatable at
                           the stand yet differ a short distance away (the wearer's head sits
                           ~0.3 m above the stand)
  Schroeder frequency      f_S = 2000 sqrt(T/V), T the room's 125 Hz T20, V the tape-measured
                           volume (the SLAM room box where none was taped, which overestimates V
                           and so underestimates f_S)
  error per band           median |T20 error| and the signed mean over takes, informed and blind
                           (results/pipeline/summary.csv, the five composite rooms, all
                           movements): whether a band is hard for the method or only for blind
                           estimation
  speech excitation        each voice's octave-band level re its 1 kHz band (the speech part of
                           the source signal of one take per voice): blind estimation sees the
                           room only through the speech
"""
from __future__ import annotations

import csv
import json
import math
from pathlib import Path

import numpy as np
import scipy.io as sio
from scipy.signal import butter, sosfilt

import stats as S

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "reliability"
ROOMS = json.loads((ROOT / "config" / "rooms.json").read_text())["rooms"]
MAIN = ("office", "corridor", "reverb", "meeting", "smallmeeting")
CONDITIONS = {"informed_motionAware": "Informed (MA)", "blind_motionAware": "Blind (MA)", "blind_omni": "Blind (Omni)"}
VOICES = {"male": "office_maleSpeech_static", "female": "office_femaleSpeech_static"}


def band_level_db(x: np.ndarray, fs: float, fc: float) -> float:
    sos = butter(4, [fc / math.sqrt(2), min(fc * math.sqrt(2), 0.95 * fs / 2)], btype="band", fs=fs, output="sos")
    return 10 * math.log10(np.mean(sosfilt(sos, x) ** 2) + 1e-30)


def main() -> int:
    ref = list(csv.DictReader(open(OUT / "ref_t20_per_sweep.csv")))
    bands = [int(k[4:]) for k in ref[0] if k.startswith("t20_")]
    head = "| " + " | ".join(f"{b} Hz" for b in bands) + " |"
    rule = "|---|" + "---|" * len(bands)
    lines = ["# Reliability of T20 per octave band\n", "Generated by `analysis/reliability.py`.\n",
             "## Reference repeatability\n",
             "The scoring's T20 estimator (`getT20Ita`) on each omni sweep separately. Cells: spread across the "
             "sweeps (max - min) as % of the T20 of their mean, the IR the scoring uses; NaN where T20, T15 and T10 "
             "all failed. An upper bound on the uncertainty of the mean; blind to position dependence.\n",
             "| Room | Sweeps " + head, "|---" + rule]
    t125 = {}
    for room in MAIN:
        rs = [r for r in ref if r["room"] == room]
        mean_ir = next(r for r in rs if r["sweep"] == "0")
        sw = [r for r in rs if r["sweep"] != "0"]
        t125[room] = float(mean_ir["t20_125"])
        cells = []
        for b in bands:
            v = np.array([float(r[f"t20_{b}"]) for r in sw])
            cells.append("NaN" if not np.isfinite(v).all() else f"{100 * (v.max() - v.min()) / float(mean_ir[f't20_{b}']):.1f} %")
        lines.append(f"| {room} | {len(sw)} | " + " | ".join(cells) + " |")

    lines += ["", "## Schroeder frequency\n",
              "f_S = 2000 sqrt(T/V), with T the room's 125 Hz T20. The 125 Hz octave spans 88-177 Hz: where f_S lies "
              "inside or above it, that band is modal and its T20 depends on position.\n",
              "| Room | V (m^3) | T20 at 125 Hz (s) | f_S (Hz) |", "|---|---|---|---|"]
    scene = list(csv.DictReader(open(ROOT / "results" / "geometry" / "scene.csv")))
    for room in MAIN:
        dims = ROOMS[room].get("dims_m")
        if dims:
            V, src = float(np.prod(dims)), "tape"
        else:
            V, src = float(np.median([float(r["V_m3"]) for r in scene if r["take"].startswith(room + "_")])), "SLAM box"
        lines.append(f"| {room} | {V:.0f} ({src}) | {t125[room]:.2f} | {2000 * math.sqrt(t125[room] / V):.0f} |")

    summ = [r for r in csv.DictReader(open(ROOT / "results" / "pipeline" / "summary.csv")) if r["take"].split("_")[0] in MAIN]
    lines += ["", "## Error per band\n",
              "Median |T20 error| over takes (%), signed mean in brackets (positive = too long). Five rooms, all "
              "movements.\n", "| Condition | Takes " + head, "|---" + rule]
    for cond, name in CONDITIONS.items():
        rs = [r for r in summ if r["condition"] == cond]
        cells = []
        for b in bands:
            v = np.array([S.num(r[f"t20Err_{b}"]) for r in rs]); v = v[np.isfinite(v)]
            cells.append(f"{np.median(np.abs(v)):.1f} ({np.mean(v):+.1f})")
        lines.append(f"| {name} | {len(rs)} | " + " | ".join(cells) + " |")
    lines += ["", "By voice (median |T20 error|, %): if weak excitation drives the blind errors, the female voice "
              "should err more where it has little energy (125 Hz, 4-8 kHz).\n",
              "| Condition | Voice | Takes " + head, "|---|---" + rule]
    for cond, name in CONDITIONS.items():
        for voice in VOICES:
            rs = [r for r in summ if r["condition"] == cond and f"_{voice}Speech_" in r["take"]]
            cells = [f"{np.nanmedian(np.abs([S.num(r[f't20Err_{b}']) for r in rs])):.1f}" for b in bands]
            lines.append(f"| {name} | {voice} | {len(rs)} | " + " | ".join(cells) + " |")

    lines += ["", "## Speech excitation\n",
              "Octave-band level of the speech (the source signal within speech_span_s) re its 1 kHz band (dB), "
              "one take per voice.\n",
              "| Voice | Take " + head, "|---" + rule]
    for voice, take in VOICES.items():
        d = sio.loadmat(ROOT / "data" / "rooms" / f"{take}.mat", variable_names=["sourceSig", "fs"], squeeze_me=True)
        x, fs = np.asarray(d["sourceSig"], float).ravel(), float(d["fs"])
        # the speech only: sourceSig starts at source_span_s, which on the composite drive still
        # holds the end of the sweep (its highest frequencies)
        rc = ROOMS[take.split("_")[0]]; tc = rc["takes"][take]
        sp, src = tc.get("speech_span_s", rc["speech_span_s"]), tc.get("source_span_s", rc["source_span_s"])
        x = x[int(round((sp[0] - src[0]) * fs)):int(round((sp[1] - src[0]) * fs))]
        L = {b: band_level_db(x, fs, b) for b in bands}
        lines.append(f"| {voice} | {take} | " + " | ".join(f"{L[b] - L[1000]:+.1f}" for b in bands) + " |")

    md = "\n".join(lines) + "\n"
    (OUT / "summary.md").write_text(md)
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
